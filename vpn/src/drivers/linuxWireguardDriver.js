import { execFile } from 'child_process';
import { promisify } from 'util';
import fs from 'fs/promises';
import { WireguardDriverInterface } from './wireguardDriverInterface.js';
import { VPN_CONFIG, VPN_STATUS, VPN_ERROR_TYPE } from '../constants/vpnConstants.js';
import { config } from '../config/env.js';
import { logger } from '../utils/logger.js';

const execFileAsync = promisify(execFile);

/**
 * 리눅스 네이티브 WireGuard 드라이버 (wg, wg-quick CLI 및 /etc/wireguard/wg0.conf 연동)
 */
export class LinuxWireguardDriver extends WireguardDriverInterface {
  constructor(options = {}) {
    super();
    this.iface = options.interface || config.wgInterface;
    this.configPath = options.configPath || config.wgConfigPath;
    this.serverPublicKey = options.serverPublicKey || config.wgServerPublicKey;
    this.serverEndpoint = options.serverEndpoint || config.wgServerEndpoint;
    this.serverIp = options.serverIp || config.wgServerIp;
    this.keepalive = options.keepalive || config.wgKeepalive;
  }

  /**
   * wg set peer 실행
   */
  async addPeer(publicKey, allowedIp, persistentKeepalive = 25) {
    const normalizedIp = allowedIp.includes('/') ? allowedIp : `${allowedIp}/32`;
    try {
      await execFileAsync('wg', [
        'set',
        this.iface,
        'peer',
        publicKey,
        'allowed-ips',
        normalizedIp,
        'persistent-keepalive',
        String(persistentKeepalive),
      ]);

      logger.info(`[LinuxWireguardDriver] wg peer 추가 성공: ${publicKey} (${normalizedIp})`);

      return {
        publicKey,
        allowedIp: normalizedIp,
        persistentKeepalive,
        vpnStatus: VPN_STATUS.CONNECTED,
        lastHandshake: new Date().toISOString(),
      };
    } catch (error) {
      logger.error(`[LinuxWireguardDriver] wg set peer 실패: ${error.message}`);
      throw error;
    }
  }

  /**
   * wg set peer remove 실행
   */
  async removePeer(publicKey) {
    try {
      await execFileAsync('wg', ['set', this.iface, 'peer', publicKey, 'remove']);
      logger.info(`[LinuxWireguardDriver] wg peer 삭제 성공: ${publicKey}`);
      return true;
    } catch (error) {
      logger.error(`[LinuxWireguardDriver] wg peer 삭제 실패: ${error.message}`);
      return false;
    }
  }

  /**
   * wg show <iface> dump 파싱하여 단일 피어 상태 반환
   */
  async getPeer(publicKey) {
    const peers = await this.getPeers();
    return peers.find((p) => p.publicKey === publicKey) || null;
  }

  /**
   * wg show <iface> dump 파싱하여 모든 피어 상태 반환
   */
  async getPeers() {
    try {
      const { stdout } = await execFileAsync('wg', ['show', this.iface, 'dump']);
      const lines = stdout.trim().split('\n');
      const peers = [];

      // 첫 줄은 서버 자체 인터페이스 정보, 2번째 줄부터 피어 정보
      for (let i = 1; i < lines.length; i++) {
        const line = lines[i].trim();
        if (!line) continue;

        // columns: public-key, preshared-key, endpoint, allowed-ips, latest-handshake, transfer-rx, transfer-tx, persistent-keepalive
        const [pubKey, , endpoint, allowedIps, latestHandshakeEpoch, rx, tx] = line.split('\t');

        const handshakeSec = parseInt(latestHandshakeEpoch, 10) || 0;
        const nowSec = Math.floor(Date.now() / 1000);
        const diffSec = nowSec - handshakeSec;

        let vpnStatus = VPN_STATUS.CONNECTED;
        let errorType = null;

        if (handshakeSec === 0) {
          vpnStatus = VPN_STATUS.DISCONNECTED;
        } else if (diffSec > VPN_CONFIG.HANDSHAKE_STALE_SEC) {
          vpnStatus = VPN_STATUS.ERROR;
          errorType = VPN_ERROR_TYPE.HANDSHAKE_TIMEOUT;
        }

        peers.push({
          publicKey: pubKey,
          endpoint: endpoint === '(none)' ? null : endpoint,
          allowedIp: allowedIps,
          lastHandshake: handshakeSec ? new Date(handshakeSec * 1000).toISOString() : null,
          rxBytes: parseInt(rx, 10) || 0,
          txBytes: parseInt(tx, 10) || 0,
          vpnStatus,
          errorType,
        });
      }

      return peers;
    } catch (error) {
      logger.error(`[LinuxWireguardDriver] wg show dump 실패: ${error.message}`);
      return [];
    }
  }

  /**
   * /etc/wireguard/wg0.conf 파일 전체 동기화
   */
  async syncConfigFile(peers) {
    const lines = [
      '# SecureCam WireGuard Server Configuration',
      '# Auto-generated by SecureCam VPN Controller',
      '[Interface]',
      `Address = ${this.serverIp}/24`,
      `ListenPort = ${config.wgPort}`,
      `PrivateKey = ${config.wgServerPrivateKey}`,
      'PostUp = iptables -A FORWARD -i wg0 -j ACCEPT; iptables -t nat -A POSTROUTING -o eth0 -j MASQUERADE',
      'PostDown = iptables -D FORWARD -i wg0 -j ACCEPT; iptables -t nat -D POSTROUTING -o eth0 -j MASQUERADE',
      '',
    ];

    for (const p of peers) {
      lines.push('[Peer]');
      if (p.name || p.deviceId) {
        lines.push(`# ${p.name || p.deviceId}`);
      }
      lines.push(`PublicKey = ${p.publicKey || p.wg_pubkey}`);
      const ip = p.allowedIp || p.vpn_ip;
      lines.push(`AllowedIPs = ${ip.includes('/') ? ip : `${ip}/32`}`);
      lines.push(`PersistentKeepalive = ${p.persistentKeepalive || this.keepalive}`);
      lines.push('');
    }

    const content = lines.join('\n');

    try {
      await fs.writeFile(this.configPath, content, { encoding: 'utf-8', mode: 0o600 });
      logger.info(`[LinuxWireguardDriver] WireGuard 설정 파일 저장 완료: ${this.configPath}`);
    } catch (err) {
      logger.warn(`[LinuxWireguardDriver] 설정 파일 쓰기 권한 부족 또는 경로 없음: ${err.message}`);
    }

    return content;
  }

  generateClientConfig(clientPrivateKey, clientIp) {
    const ipOnly = clientIp.includes('/') ? clientIp.split('/')[0] : clientIp;

    return [
      '[Interface]',
      `PrivateKey = ${clientPrivateKey}`,
      `Address = ${ipOnly}/24`,
      '',
      '[Peer]',
      `PublicKey = ${this.serverPublicKey}`,
      `Endpoint = ${this.serverEndpoint}`,
      `AllowedIPs = ${VPN_CONFIG.SUBNET}`,
      `PersistentKeepalive = ${this.keepalive}`,
      '',
    ].join('\n');
  }

  async reloadInterface() {
    try {
      await execFileAsync('wg', ['syncconf', this.iface, '<(wg-quick', 'strip', this.iface + ')'], { shell: true });
      logger.info(`[LinuxWireguardDriver] wg syncconf 완료: ${this.iface}`);
      return true;
    } catch (error) {
      logger.error(`[LinuxWireguardDriver] wg reload 실패: ${error.message}`);
      return false;
    }
  }
}
